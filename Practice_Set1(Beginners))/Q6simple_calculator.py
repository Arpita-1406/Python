'''Write a program that:
1. Takes two numbers as input from the user.
2. Prints their sum, difference, product, and quotient.'''

a =float(input("Enter a first number: "))
b =float(input("Enter a second number: ")) 

print("a + b = ", a + b)
print("a - b = ", a - b)
print("a * b = ", a * b)
print("a / b = ", a / b)
print("a % b = ", a % b)
